#!/usr/bin/env python3
"""Local editable DOT focused diagrams. No runtime calls, networking or installs."""
from pathlib import Path
import json,subprocess,textwrap,html,re,os,tempfile,argparse
os.environ.setdefault("XDG_CACHE_HOME", str(Path(tempfile.gettempdir()) / "brain-visual-font-cache"))
P=Path(__file__).resolve().parent.parent
x=json.loads((P/'source/focused-flows.json').read_text())
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--only', nargs='+', choices=[d['id'] for d in x['diagrams']], help='Render only named diagrams; others remain untouched.')
selected=parser.parse_args().only
# These dense graphs need their edge labels above every path, not only within
# each edge group. The topology, text, coordinates and node placement stay intact.
TOP_LABEL_IDS={'focus-authority-revocation','focus-cognitive-loop','focus-memory-lifecycle'}
def topmost_edge_labels(svg, layout):
 labels=[]
 def move(match):
  group=match.group(0)
  labels.extend(re.findall(r'<text\b.*?</text>',group,re.S))
  return re.sub(r'<text\b.*?</text>\s*','',group,flags=re.S)
 svg=re.sub(r'<g\b[^>]*class="edge"[^>]*>.*?</g>',move,svg,flags=re.S)
 # Use Graphviz's own text extents for white knockouts; do not guess widths.
 backgrounds=[]
 for edge in layout['edges']:
  size=14.0
  for op in edge.get('_ldraw_',[]):
   if op['op']=='F':size=op['size']
   if op['op']=='T':
    cx,cy=op['pt'];w=op['width']
    left=cx-w/2 if op['align']=='c' else cx-w if op['align']=='r' else cx
    backgrounds.append(f'<rect x="{left-3:g}" y="{-cy-size:g}" width="{w+6:g}" height="{size+5:g}" fill="white" stroke="none"/>')
 layer='<g class="edge-labels">\n'+'\n'.join(backgrounds+labels)+'\n</g>\n'
 at=svg.rfind('</g>')
 return svg[:at]+layer+svg[at:]
COL={'data':'#087f8c','control':'#9a5b06','provenance':'#7451a8'}
def q(x):return json.dumps(x,ensure_ascii=False)
def wrap(x,n):return '\n'.join(textwrap.wrap(x,n,break_long_words=False))
ranks={
'focus-cognitive-loop':[['human','ingress'],['plan','stop'],['candidate'],['review','custody'],['orient','tel']],
'focus-authority-revocation':[['human'],['draft','adopt','business'],['screen','admit'],['effect','recover'],['history']],
'focus-memory-lifecycle':[['material','custody'],['posture','owner'],['index','lifecycle'],['retrieve','use'],['consumer','influence']],
'focus-three-node':[['a_request'],['a_release'],['b_admit','c_admit'],['b_work','c_review'],['a_use'],['a_result','histories']]}
for d in x['diagrams']:
 if selected and d['id'] not in selected:continue
 name=d['id'];out=['digraph G {','graph [rankdir=TB, bgcolor="white", pad="0.4", nodesep="0.8", ranksep="0.8", splines=spline, overlap=false, outputorder=edgesfirst, fontname="DejaVu Sans", labelloc=t, fontsize=26, label='+q(wrap(d['title'],65)+'\n\nINTENDED FLOW · NOT IMPLEMENTED-EDGE EVIDENCE\nTeal: data | Amber: control | Purple: provenance\nAll nodes reference primary homes in the module index.')+'];','node [shape=box, style="rounded,filled", fillcolor="#f0f7f7", color="#a2bcc0", penwidth=1.4, fontname="DejaVu Sans", fontsize=18, margin="0.18,0.15"];','edge [fontname="DejaVu Sans", fontsize=14, penwidth=1.8, arrowsize=0.8, style=dashed];']
 for n in d['nodes']:
  out.append(q(n['id'])+' [label='+q(wrap(n['label'],29)+'\n'+', '.join(n['family_ids']))+'];')
 for row in ranks[name]:out.append('{rank=same; '+';'.join(q(v) for v in row)+';}')
 for e in d['edges']:
  out.append(q(e['from'])+' -> '+q(e['to'])+' [color='+q(COL[e['type']])+', fontcolor='+q(COL[e['type']])+', label='+q(wrap(e['label'],27))+'];')
 out.append('}');dot=P/'source'/(name+'.dot');dot.write_text('\n'.join(out)+'\n')
 for fmt in ['svg']:
  subprocess.run(['dot', '-T'+fmt,'-Gdpi=72',str(dot),'-o',str(P/fmt/(name+'.'+fmt))],check=True)
 svg=P/'svg'/(name+'.svg');t=svg.read_text();t=t.replace('<svg ', '<svg role="img" aria-label='+html.escape(q(d['title']),quote=False)+' ',1);t=t.replace('<!-- Generated by graphviz', '<!-- Generated by graphviz',1);pos=t.index('>\n',t.index('<svg '))+2;t=t[:pos]+'<desc>'+html.escape(d['caption']+' '+' '.join(d['notes']))+'</desc>\n'+t[pos:];t=t.replace('<desc>', '<style>g.edge text, g.edge-labels text { paint-order: stroke; stroke: white; stroke-width: 5px; stroke-linejoin: round; }</style><desc>',1);
 if name not in TOP_LABEL_IDS:t=t.replace('g.edge text, g.edge-labels text', 'g.edge text')
 if name in TOP_LABEL_IDS:
  layout=json.loads(subprocess.check_output(['dot','-Tjson',str(dot)]))
  t=topmost_edge_labels(t,layout)
 svg.write_text(t)
 subprocess.run(['inkscape',str(svg),'--export-type=png','--export-width=1600','--export-filename='+str(P/'png'/(name+'.png'))],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
print('Rendered '+str(len(selected) if selected else len(x['diagrams']))+' intended focus flows.')
